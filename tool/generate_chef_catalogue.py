"""Generate shared Chef identities from the existing sourced CoFID asset.

Only deliberately curated ready-to-assemble foods are allowed. No nutrient facts
are sent to the model. This tool has no network access.
"""
import json
from pathlib import Path

READY_CODES = {
    '14-319', '14-318', '11-981', '13-509', '12-550', '18-323',
    '13-523', '13-661', '13-658', '13-490', '11-858', '13-496',
    '13-517', '13-519', '12-379', '12-184', '11-789', '16-440',
}
VERSION = 'cofid-2021-ready-v1'


def metadata(data):
    foods = []
    for row in data['foods']:
        if row['food_code'] not in READY_CODES:
            continue
        if (row['id'] != 'cofid_2021_' + row['food_code']
                or not isinstance(row['name'], str) or not 1 <= len(row['name']) <= 80):
            raise ValueError('Invalid source identity')
        foods.append({'recordId': 'imported_' + row['id'], 'name': row['name']})
    if len(foods) != len(READY_CODES) or len({f['recordId'] for f in foods}) != len(foods):
        raise ValueError('Missing or duplicate curated Chef identity')
    return {'version': VERSION, 'foods': foods}


def main():
    root = Path(__file__).resolve().parents[1]
    data = json.loads((root / 'assets/data/food_catalog.json').read_text(encoding='utf-8'))
    result = metadata(data)
    shared = root / 'shared'
    shared.mkdir(exist_ok=True)
    (shared / 'chef_catalogue.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    js = ('// Generated by tool/generate_chef_catalogue.py; identities only, no nutrients.\n'
          'export const chefCatalogueVersion = ' + json.dumps(result['version']) + ';\n'
          'export const chefCatalogue = Object.freeze(' + json.dumps(result['foods'], ensure_ascii=False, indent=2)
          + '.map(Object.freeze));\n')
    (root / 'server/src/chef_catalogue.mjs').write_text(js, encoding='utf-8')
    print(f'Generated {len(result["foods"])} ready-to-assemble Chef identities')


if __name__ == '__main__':
    main()
